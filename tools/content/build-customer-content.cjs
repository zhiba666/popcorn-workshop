'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { createBuildOutput } = require('../assets/build-output.cjs');

const root = path.resolve(__dirname, '../..');
const fields = ['customers', 'relationshipLabels', 'thresholds', 'rewardMultipliers', 'baseReward'];

function readContent(sourcePath) {
  const content = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
  for (const field of fields.slice(0, -1)) {
    if (!Array.isArray(content[field])) throw new Error(`Customer content ${field} must be an array.`);
  }
  if (!Number.isFinite(content.baseReward) || content.baseReward < 3) {
    throw new Error('Customer content baseReward must be a finite number of at least 3.');
  }
  if (!content.thresholds.length || content.relationshipLabels.length !== content.thresholds.length
      || content.rewardMultipliers.length !== content.thresholds.length) {
    throw new Error('Customer relationship labels, thresholds, and reward multipliers must have matching lengths.');
  }
  if (content.thresholds.some((value, index) => !Number.isInteger(value) || value < 1
      || (index > 0 && value <= content.thresholds[index - 1]))) {
    throw new Error('Customer relationship thresholds must be positive, increasing integers.');
  }
  if (content.rewardMultipliers.some(value => !Number.isFinite(value) || value < 0)) {
    throw new Error('Customer reward multipliers must be finite, nonnegative numbers.');
  }
  const ids = new Set();
  for (const customer of content.customers) {
    if (!customer || typeof customer.id !== 'string' || !customer.id || ids.has(customer.id)) {
      throw new Error('Customer IDs must be nonempty, unique strings.');
    }
    ids.add(customer.id);
    if (!Array.isArray(customer.stages) || !Array.isArray(customer.daily)) {
      throw new Error(`Customer ${customer.id} must have stages and daily arrays.`);
    }
  }
  // Keep the generated field order independent of object key order in the source.
  return Object.fromEntries(fields.map(field => [field, content[field]]));
}

function buildCustomerContent({ check = false, root: projectRoot = root } = {}) {
  const sourcePath = path.join(projectRoot, 'content/customers/customers.json');
  const outputPaths = [
    path.join(projectRoot, 'douyin-game/src/generated/customer-content.js'),
    path.join(projectRoot, 'preview/_generated/customer-content.js'),
  ];
  const content = readContent(sourcePath);
  // The original CLI remains a supported facade. Keep this stable for preview
  // servers that were started before the tool directory migration.
  const header = '// Generated from content/customers/customers.json by tools/build-customer-content.cjs.\n'
    + '// Edit the source JSON and regenerate; do not edit this file directly.\n';
  const data = `const customerContent = ${JSON.stringify(content, null, 2)};\n`;
  const outputs = [
    `'use strict';\n\n${header}${data}\nmodule.exports = customerContent;\n`,
    `${header}${data}\nexport const { ${fields.join(', ')} } = customerContent;\n`,
  ];
  const changed = [];
  for (let index = 0; index < outputPaths.length; index += 1) {
    const outputPath = outputPaths[index];
    const expected = outputs[index];
    if (fs.existsSync(outputPath) && fs.readFileSync(outputPath, 'utf8') === expected) continue;
    changed.push(path.relative(projectRoot, outputPath));
  }
  if (check && changed.length) {
    throw new Error(`Generated customer content is out of date: ${changed.join(', ')}. Run node tools/content/build-customer-content.cjs.`);
  }
  if (!check && changed.length) {
    // Share asset ownership and its lock with full/scene builds. Publish both
    // module formats together, and refuse to replace an edited generated file.
    // The release builder also calls this in its isolated staging workspace.
    const transaction = createBuildOutput({ root: projectRoot,
      allowedRoots: ['assets/runtime', 'douyin-game/assets', 'douyin-game/src/generated', 'preview/_generated'],
      manifestPath: 'assets/build-outputs.json', scope: 'shared', prune: false });
    try {
      for (let index = 0; index < outputPaths.length; index += 1) {
        transaction.write(path.relative(projectRoot, outputPaths[index]).replace(/\\/g, '/'), outputs[index]);
      }
      transaction.commit({ validate() {
        if (JSON.stringify(readContent(sourcePath)) !== JSON.stringify(content)) {
          throw new Error('Customer content changed while building; retry the content build.');
        }
      } });
    } catch (error) { transaction.abort(); throw error; }
  }
  return changed;
}

function runCli() {
  try {
    if (process.argv.slice(2).some(argument => argument !== '--check')) {
      throw new Error('Usage: node tools/content/build-customer-content.cjs [--check]');
    }
    const check = process.argv.includes('--check');
    const changed = buildCustomerContent({ check });
    console.log(check ? 'Generated customer content is up to date.' : `Generated customer content: ${changed.length} file(s) updated.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { buildCustomerContent, runCli };
if (require.main === module) runCli();
